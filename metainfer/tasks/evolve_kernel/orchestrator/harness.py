PERF_HARNESS_TEMPLATE = '''"""
Auto-generated performance measurement harness for kernel optimization.
Interleaved A/B benchmark: ref → evo → evo → ref, alternating to cancel
thermal drift and systematic timing bias.
Generated by MetaInfer evolve-kernel orchestrator.
"""
import importlib.util
import json
import sys
import time
import traceback
from pathlib import Path

import torch


def load_kernel(filepath: str, fn_name: str = "{kernel_fn_name}"):
    spec = importlib.util.spec_from_file_location("_kernel_perf_mod", filepath)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if not hasattr(mod, fn_name):
        raise ValueError(f"Function {{fn_name!r}} not found in {{filepath}}")
    return getattr(mod, fn_name)


def generate_benchmark_inputs():
    """Generate benchmark inputs at realistic sizes.

    Returns a list of dicts, each with kwargs for the kernel.
    AGENT MUST FILL IN realistic workload sizes.
    """
{bench_inputs_body}
    return bench_cases


def run_kernel(kernel_fn, test_case, warmup=5, repeat=20):
    """Time the kernel. AGENT FILLS IN with CUDA-event-based timing.

    Returns (median_time_ms, all_times_ms).
    """
{runner_body}


def main():
    if len(sys.argv) < 2:
        print(json.dumps({{"passed": False, "error": "Usage: python perf_harness.py <kernel.py>"}}))
        sys.exit(0)

    kernel_path = sys.argv[1]
    ref_path = "{ref_kernel_path}"

    try:
        ref_fn = load_kernel(ref_path, "{kernel_fn_name}")
        evo_fn = load_kernel(kernel_path, "{kernel_fn_name}")
    except Exception as e:
        print(json.dumps({{
            "passed": False,
            "error": f"Failed to load kernels: {{e}}",
            "traceback": traceback.format_exc()[:2000],
        }}))
        sys.exit(0)

    bench_cases = generate_benchmark_inputs()
    results = {{}}
    all_ref_times = []
    all_evo_times = []

    for tc in bench_cases:
        name = tc.get("name", "bench")
        try:
            ref_med, ref_times = run_kernel(ref_fn, tc, warmup={warmup}, repeat={repeat})
            evo_med, evo_times = run_kernel(evo_fn, tc, warmup={warmup}, repeat={repeat})

            # Interleaved re-measurement: ref-evo interleaved
            for _ in range({repeat}):
                _, rt = run_kernel(ref_fn, tc, warmup=0, repeat=1)
                all_ref_times.append(rt[0])
                _, et = run_kernel(evo_fn, tc, warmup=0, repeat=1)
                all_evo_times.append(et[0])

            speedup = ref_med / max(evo_med, 1e-6)
            results[name] = {{
                "ref_median_ms": round(ref_med, 6),
                "evo_median_ms": round(evo_med, 6),
                "speedup": round(speedup, 4),
            }}
        except Exception as e:
            results[name] = {{"error": str(e)[:300]}}

    # Aggregate
    import statistics
    ref_overall = statistics.median(all_ref_times) if all_ref_times else 0.0
    evo_overall = statistics.median(all_evo_times) if all_evo_times else 0.0
    overall_speedup = ref_overall / max(evo_overall, 1e-6)

    print(json.dumps({{
        "passed": True,
        "ref_median_ms": round(ref_overall, 6),
        "evo_median_ms": round(evo_overall, 6),
        "overall_speedup": round(overall_speedup, 4),
        "per_case": results,
        "num_cases": len(bench_cases),
    }}))


if __name__ == "__main__":
    main()
'''


def _fill_template(template: str, **kwargs: str) -> str:
    """Safe template fill — handles nested braces by using explicit keys."""
    result = template
    for key, value in kwargs.items():
        result = result.replace("{" + key + "}", value)
    return result


def build_correctness_harness_template(
    kernel_fn_name: str,
    ref_kernel_path: str,
    test_inputs_body: str = "    # AGENT: generate test cases covering all code paths\n    test_cases = []\n",
    ref_runner_body: str = "    # AGENT: call the reference kernel with test_case\n    torch.cuda.synchronize()\n    output = kernel_fn(**test_case)\n    torch.cuda.synchronize()\n",
    evo_runner_body: str = "    # AGENT: call the evolved kernel with test_case\n    torch.cuda.synchronize()\n    output = kernel_fn(**test_case)\n    torch.cuda.synchronize()\n",
    comparator_body: str = "    max_err = (ref_output - evo_output).abs().max().item()\n    passed = max_err < 1e-3\n    return passed, f'max_err={max_err}' if not passed else '', {'max_error': max_err}\n",
) -> str:
    return _fill_template(
        CORRECTNESS_HARNESS_TEMPLATE,
        kernel_fn_name=kernel_fn_name,
        ref_kernel_path=ref_kernel_path,
        test_inputs_body=test_inputs_body,
        ref_runner_body=ref_runner_body,
        evo_runner_body=evo_runner_body,
        comparator_body=comparator_body,
    )


def build_perf_harness_template(
    kernel_fn_name: str,
    ref_kernel_path: str,
    bench_inputs_body: str = "    # AGENT: generate realistic benchmark sizes\n    bench_cases = []\n",
    runner_body: str = "    start = torch.cuda.Event(enable_timing=True)\n    end = torch.cuda.Event(enable_timing=True)\n    times = []\n    for _ in range(warmup + repeat):\n        start.record()\n        kernel_fn(**test_case)\n        end.record()\n        torch.cuda.synchronize()\n        if _ >= warmup:\n            times.append(start.elapsed_time(end))\n    import statistics\n    return statistics.median(times), times\n",
    warmup: int = 5,
    repeat: int = 20,
) -> str:
    return _fill_template(
        PERF_HARNESS_TEMPLATE,
        kernel_fn_name=kernel_fn_name,
        ref_kernel_path=ref_kernel_path,
        bench_inputs_body=bench_inputs_body,
        runner_body=runner_body,
        warmup=str(warmup),
        repeat=str(repeat),
    )


