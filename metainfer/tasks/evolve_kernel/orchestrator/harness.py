def run_correctness_test(
    harness_path: Path,
    evolved_kernel_path: Path,
    timeout_s: int = 300,
) -> Tuple[bool, Dict[str, Any]]:
    """Run the correctness harness against an evolved kernel.

    Returns (passed, parsed_output_dict).
    """
    env = dict(os.environ)
    env["METAINFER_KERNEL_PATH"] = str(evolved_kernel_path)

    try:
        proc = subprocess.run(
            ["python3", str(harness_path), str(evolved_kernel_path)],
            capture_output=True, text=True,
            timeout=timeout_s, env=env,
        )
    except subprocess.TimeoutExpired:
        return False, {"passed": False, "error": f"Correctness harness timed out after {timeout_s}s"}
    except Exception as e:
        return False, {"passed": False, "error": f"Failed to run harness: {e!r}"}

    # Parse JSON from stdout (last line or last JSON object)
    stdout = proc.stdout or ""
    parsed = _extract_json(stdout)
    if parsed is None:
        # Try stderr
        stderr = proc.stderr or ""
        parsed_stderr = _extract_json(stderr)
        if parsed_stderr is None:
            return False, {
                "passed": False,
                "error": f"Harness produced no parseable JSON. stdout tail: {stdout[-500:]!r}",
            }
        parsed = parsed_stderr

    passed = bool(parsed.get("passed", False))
    return passed, parsed


def run_perf_test(
    harness_path: Path,
    kernel_path: Path,
    timeout_s: int = 600,
) -> Tuple[bool, Dict[str, Any]]:
    """Run the performance harness against a kernel.

    Returns (success, parsed_output_dict with exec_time_ms).
    """
    env = dict(os.environ)
    env["METAINFER_KERNEL_PATH"] = str(kernel_path)

    try:
        proc = subprocess.run(
            ["python3", str(harness_path), str(kernel_path)],
            capture_output=True, text=True,
            timeout=timeout_s, env=env,
        )
    except subprocess.TimeoutExpired:
        return False, {"passed": False, "error": f"Perf harness timed out after {timeout_s}s"}
    except Exception as e:
        return False, {"passed": False, "error": f"Failed to run perf harness: {e!r}"}

    stdout = proc.stdout or ""
    parsed = _extract_json(stdout)
    if parsed is None:
        stderr = proc.stderr or ""
        parsed = _extract_json(stderr) or {}
        parsed["passed"] = False

    passed = bool(parsed.get("passed", False))
    return passed, parsed


def _extract_json(text: str) -> Optional[Dict[str, Any]]:
    """Extract the last valid JSON object from text output."""
    candidates = []
    for ln in reversed(text.splitlines()):
        ln = ln.strip()
        if ln.startswith("{") and ln.endswith("}"):
            candidates.append(ln)
            if len(candidates) >= 10:
                break

    for c in candidates:
        try:
            obj = json.loads(c)
            if isinstance(obj, dict):
                return obj
        except json.JSONDecodeError:
            continue

    # Fallback: try to find JSON block in full text
    import re
    m = re.search(r'\{[^{}]*"passed"[^{}]*\}', text)
    if m:
        try:
            return json.loads(m.group(0))
        except json.JSONDecodeError:
            pass

    return None
